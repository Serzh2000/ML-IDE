@dataclass
class Advice:
    level: str       # ok | info | warn
    title: str
    text: str


def _labeled(project):
    return [e for e in project.images if [a for a in e.anns if not a.suggested] or e.tag is not None]


def analyze(project):
    """Возвращает (settings, advice). settings - ключи project.export."""
    adv: list[Advice] = []
    lab = _labeled(project)
    n = len(lab)
    names = project.class_names()
    counts = [0] * len(names)
    sides = []
    n_poly = n_box = 0
    for e in lab:
        for a in e.anns:
            if a.suggested:
                continue
            if 0 <= a.cls < len(counts):
                counts[a.cls] += 1
            x1, y1, x2, y2 = a.bbox()
            sides.append(math.sqrt(max(1e-9, (x2 - x1) * (y2 - y1))) * 640 / max(e.w, e.h))
            n_poly += a.kind == "poly"
            n_box += a.kind == "box"
    for e in lab:                      # классификация: класс кадра считается за один пример
        if e.tag is not None and 0 <= e.tag < len(counts):
            counts[e.tag] += 1
    total = sum(counts)
    gpu = shutil.which("nvidia-smi") is not None
    med = float(np.median(sides)) if sides else 100.0
    small_frac = float(np.mean(np.array(sides) < 16)) if sides else 0.0

    if n == 0:
        adv.append(Advice("warn", "Нет размеченных изображений", "Разметьте хотя бы 30-50 картинок, и советник сможет "
                          "дать рекомендации."))
        return {}, adv

    # --- объём данных
    if n < 30:
        adv.append(Advice("warn", f"Очень мало данных ({n} изображений)",
                          "Этого хватит лишь проверить идею. Разметьте 100+ изображений. Дальше пригодится "
                          "авторазметка: обучите первую модель на том, что есть, и пусть она размечает остальное."))
    elif n < 200:
        adv.append(Advice("info", f"Небольшой датасет ({n} изображений)",
                          "Для простых задач с однотипными условиями достаточно. Включена сильная аугментация и "
                          "маленькая модель, чтобы избежать переобучения."))
    else:
        adv.append(Advice("ok", f"Размер датасета нормальный ({n} изображений, {total} объектов)",
                          "Можно брать модель побольше и умеренную аугментацию."))

    # --- классы
    few = [f"{names[i]} ({c})" for i, c in enumerate(counts) if c < 30]
    if few:
        adv.append(Advice("warn", "Мало примеров у классов", "Менее 30 объектов: " + ", ".join(few) +
                          ". Такие классы модель будет путать или пропускать - доразметьте до 50-100+."))
    nz = [c for c in counts if c > 0]
    if len(nz) >= 2 and max(nz) / min(nz) > 10:
        adv.append(Advice("warn", "Дисбаланс классов",
                          f"Самого частого класса в {max(nz) / min(nz):.0f} раз больше, чем самого редкого. "
                          "Модель будет «лениться» на редких. Доразметьте редкие классы."))
    empty = [names[i] for i, c in enumerate(counts) if c == 0]
    if empty:
        adv.append(Advice("info", "Классы без объектов", "Нет разметки для: " + ", ".join(empty) +
                          ". Удалите их или разметьте - иначе они лишь занимают место в модели."))

    # --- размер объектов
    imgsz = 640
    if small_frac > 0.5 or med < 20:
        imgsz = 1280 if med < 10 else 960
        adv.append(Advice("warn", "Много мелких объектов",
                          f"Медианный объект ≈ {med:.0f} px при imgsz 640 ({100 * small_frac:.0f}% меньше 16 px). "
                          f"Рекомендуется imgsz {imgsz}; это замедлит обучение. Альтернатива - обучать по тайлам."))
    elif med > 300:
        adv.append(Advice("info", "Крупные объекты", f"Объекты занимают большую часть кадра (≈{med:.0f} px). "
                          "imgsz 640 достаточно; можно даже 480 для скорости."))
    else:
        adv.append(Advice("ok", "Размер объектов подходит для imgsz 640", f"Медианный объект ≈ {med:.0f} px."))

    # --- аугментация / отражения
    risky = [nm for nm in names if any(k in nm.lower() for k in ("left", "right", "лев", "прав", "arrow", "стрел",
                                                                   "text", "текст", "digit", "цифр"))]
    if risky:
        adv.append(Advice("warn", "Осторожно с зеркальным отражением",
                          "Названия классов (" + ", ".join(risky) + ") похожи на зависящие от стороны/направления. "
                          "Отражение по горизонтали сделает их неотличимыми - в пресете поставьте «Отражение по "
                          "горизонтали» = 0."))

    # --- смешанные типы
    if n_poly and n_box:
        adv.append(Advice("info", "Смешаны рамки и полигоны",
                          "В Detection-формате полигоны превращаются в охватывающие рамки, в Segmentation рамки "
                          "станут прямоугольными масками. Для сегментации размечайте всё полигонами/«Умным контуром»."))
    elif n_poly and not n_box:
        adv.append(Advice("info", "Вся разметка - полигоны", "Для контуров выбирайте формат Segmentation (-seg модели)."))

    # --- процесс
    unrev = sum(1 for e in lab if not e.reviewed)
    sug = sum(1 for e in project.images for a in e.anns if a.suggested)
    if sug:
        adv.append(Advice("warn", f"Есть непринятые подсказки ({sug})",
                          "Они не попадут в экспорт. Просмотрите их (фильтр «С подсказками») и примите клавишей Y."))
    if unrev and unrev == n:
        adv.append(Advice("info", "Ни одно изображение не отмечено проверенным",
                          "Используйте R, чтобы отмечать просмотренные. В экспорте можно оставить только проверенные."))
    unl = len(project.images) - n
    if unl:
        adv.append(Advice("info", f"Есть неразмеченные изображения ({unl})",
                          "Если на них точно нет объектов - можно добавить как фон (опция в экспорте, до ~10% датасета). "
                          "Если объекты есть - разметьте, иначе модель научится их игнорировать."))
    if not gpu:
        adv.append(Advice("info", "Видеокарта Nvidia не обнаружена",
                          "Обучение на CPU медленное. Для быстрого результата загрузите папку экспорта в Google Colab/"
                          "Kaggle (бесплатная GPU) или оставьте модель n и imgsz 640."))

    # --- настройки
    size = "n" if (n < 300 or not gpu) else ("s" if n < 1500 else "m")
    epochs = 200 if n < 100 else 150 if n < 500 else 100 if n < 2000 else 60
    if not gpu:
        epochs = min(epochs, 60)
        imgsz = min(imgsz, 960)
    preset = "Сильная" if n < 150 else ("Средняя (по умолчанию YOLO)" if n < 1000 else "Лёгкая")
    settings = {
        "preset": preset, "epochs": epochs, "imgsz": imgsz, "size": size, "batch": 16,
        "bake_aug": n < 100,
        "train_pct": 80 if n < 300 else 70, "val_pct": 20, "test_pct": 0 if n < 300 else 10,
        "online_aug": True,
        # на малых данных дообучаем бережно: замораживаем backbone и берём небольшой шаг
        "freeze": 10 if n < 300 else 0, "lr0": 0.001 if n < 300 else 0.0, "patience": 30 if n < 300 else 100,
    }
    why = (f"Модель <b>{size}</b> (данных {n}{'' if gpu else ', нет GPU'}), эпох <b>{epochs}</b>, imgsz <b>{imgsz}</b>, "
           f"аугментация «<b>{preset}</b>»")
    adv.insert(0, Advice("ok", "Рекомендуемые настройки", why + ". Кнопка «Применить» подставит их в экспорт."))
    return settings, adv


