def _col(row, *keys):
    for k in keys:
        for kk in row:
            if kk.strip() == k:
                try:
                    return float(row[kk])
                except (TypeError, ValueError):
                    return None
    return None


def parse_rows(rows):
    """rows: list[dict] из results.csv -> dict серий."""
    S = {k: [] for k in ("epoch", "tbox", "tcls", "vbox", "vcls", "p", "r", "map50", "map", "acc")}
    for r in rows:
        ep = _col(r, "epoch")
        if ep is None:
            continue
        S["epoch"].append(ep)
        S["tbox"].append(_col(r, "train/box_loss", "train/loss"))          # train/loss - классификация
        S["tcls"].append(_col(r, "train/cls_loss"))
        S["vbox"].append(_col(r, "val/box_loss", "val/loss"))
        S["vcls"].append(_col(r, "val/cls_loss"))
        S["p"].append(_col(r, "metrics/precision(B)", "metrics/precision(M)"))
        S["r"].append(_col(r, "metrics/recall(B)", "metrics/recall(M)"))
        S["map50"].append(_col(r, "metrics/mAP50(B)", "metrics/mAP50(M)"))
        S["map"].append(_col(r, "metrics/mAP50-95(B)", "metrics/mAP50-95(M)"))
        S["acc"].append(_col(r, "metrics/accuracy_top1"))
    return S


def _clean(v):
    return [x for x in v if x is not None and not math.isnan(x)]


def _slope(v):
    v = _clean(v)
    if len(v) < 3:
        return 0.0
    x = np.arange(len(v))
    return float(np.polyfit(x, v, 1)[0])


def explain_training(S, total_epochs, finished=False):
    """Возвращает список (level, заголовок, текст) на человеческом языке."""
    out = []
    ep = len(S["epoch"])
    if ep == 0:
        return [("info", "Обучение запускается",
                 "Идёт подготовка: проверка датасета, загрузка предобученных весов (первый раз - скачивание из "
                 "интернета), построение кэша. Первая эпоха появится через несколько минут (на CPU - дольше).")]
    cur = int(S["epoch"][-1])
    total = total_epochs or max(cur, 1)
    pct = 100 * cur / total
    out.append(("info", f"Этап: эпоха {cur} из {total} ({pct:.0f}%)",
                "Каждая эпоха - один проход по всем обучающим картинкам. После каждой модель проверяется на "
                "проверочных (val) данных - по ним строятся метрики справа."))

    acc = _clean(S.get("acc", []))
    if acc and not _clean(S["map50"]):                       # классификация изображений
        v = acc[-1]
        band = "слабо" if v < 0.5 else "средне" if v < 0.8 else "хорошо" if v < 0.95 else "отлично"
        out.append(("ok" if v >= 0.8 else "warn" if v < 0.5 and ep > 10 else "info", "Качество сейчас",
                    f"Точность (top-1) = {v:.2f} - это «{band}»: модель правильно называет класс примерно у {100 * v:.0f}% проверочных "
                    f"картинок. Лучшая за обучение: {max(acc):.2f}. Если классы мало отличаются друг от друга, проверьте, что картинки "
                    "разложены по классам правильно и что в каждом классе достаточно примеров."))
    m50 = _clean(S["map50"])
    p, r = _clean(S["p"]), _clean(S["r"])
    if ep < 4:
        out.append(("info", "Старт: метрики ещё около нуля - это нормально",
                    "Первые 3-10 эпох модель «разогревается» (warmup). Оценивайте результат не раньше, чем через "
                    "10-20 эпох."))
    if m50:
        v = m50[-1]
        band = ("слабо" if v < 0.3 else "средне" if v < 0.6 else "хорошо" if v < 0.85 else "отлично")
        lvl = "warn" if v < 0.3 and ep > 15 else "ok" if v >= 0.6 else "info"
        txt = (f"mAP50 = {v:.2f} - это «{band}». Простыми словами: модель находит и правильно называет примерно "
               f"{100 * v:.0f}% объектов на проверочных картинках (грубая оценка).")
        if v < 0.3 and ep > 15:
            txt += (" Для такой стадии низко: проверьте, что размечены ВСЕ объекты, достаточно ли примеров на "
                    "класс (Инструменты → Статистика) и нет ли ошибочных классов.")
        out.append((lvl, "Качество сейчас", txt))
        best_i = int(np.argmax(m50))
        since = len(m50) - 1 - best_i
        out.append(("info", "Лучшая эпоха", f"Максимум mAP50 = {m50[best_i]:.3f} на эпохе {int(S['epoch'][best_i])}. "
                    "Именно эта версия сохраняется как best.pt - её и берите для работы."))
        if len(m50) >= 10 and m50[-1] < 0.7 * m50[best_i] and best_i < len(m50) - 5:
            out.append(("warn", "Качество упало относительно лучшей эпохи",
                        f"Сейчас mAP50 = {m50[-1]:.2f}, а лучшая была {m50[best_i]:.2f} (эпоха "
                        f"{int(S['epoch'][best_i])}). Обычно так бывает на очень малых данных: модель дообучается и "
                        "«портит» то, что умела. Попробуйте: больше данных, меньше эпох, заморозку слоёв (freeze=10) "
                        "или меньший learning rate (lr0=0.002)."))
        if since >= 15 and not finished:
            out.append(("warn", "Рост остановился",
                        f"Уже {since} эпох mAP не улучшается. Модель, вероятно, достигла потолка на этих данных. "
                        "Можно остановить обучение: дальше растёт риск переобучения, а улучшить результат помогут "
                        "новые данные, а не новые эпохи."))
        elif len(m50) >= 6 and _slope(m50[-10:]) > 0.002:
            out.append(("ok", "Модель продолжает улучшаться", "Качество уверенно растёт - пусть обучение идёт дальше."))

    # переобучение: val loss растёт, train падает
    vb, tb = _clean(S["vbox"]), _clean(S["tbox"])
    if len(vb) >= 12 and len(tb) >= 12:
        sv, st = _slope(vb[-8:]), _slope(tb[-8:])
        vmin_i = int(np.argmin(vb))
        vmin, vlast = vb[vmin_i], vb[-1]
        if (sv > 0 and st < 0) or (vlast > 1.1 * vmin and tb[-1] < tb[0]):
            out.append(("warn", "Признаки переобучения",
                        f"Ошибка на обучающих картинках упала ({tb[0]:.2f} → {tb[-1]:.2f}), а на проверочных хуже, "
                        f"чем была: минимум {vmin:.2f} (эпоха {int(S['epoch'][vmin_i])}), сейчас {vlast:.2f}. "
                        "Модель подгоняется под обучающие данные. Возьмите best.pt; для улучшения - больше разных "
                        "данных, сильнее аугментация, модель поменьше, меньше эпох."))
        elif st < 0 and sv <= 0:
            out.append(("ok", "Потери снижаются на обеих выборках", "Это здоровая картина: модель обобщает, а не заучивает."))
    elif tb and len(tb) >= 5 and _slope(tb) > 0:
        out.append(("warn", "Потери растут", "Ошибка на обучении не падает. Проверьте разметку и learning rate "
                    "(не меняли ли вы его вручную)."))

    # precision / recall
    if p and r and ep >= 8:
        if p[-1] - r[-1] > 0.2:
            out.append(("info", f"Precision ({p[-1]:.2f}) выше Recall ({r[-1]:.2f}): модель осторожничает",
                        "Что она находит - обычно верно, но часть объектов пропускает. Проверьте полноту разметки, "
                        "увеличьте imgsz для мелких объектов, добавьте примеров."))
        elif r[-1] - p[-1] > 0.2:
            out.append(("info", f"Recall ({r[-1]:.2f}) выше Precision ({p[-1]:.2f}): много ложных срабатываний",
                        "Модель находит почти всё, но и «видит» лишнее. Добавьте фоновые картинки без объектов и "
                        "более разнообразные данные; в работе поднимите порог уверенности."))
        else:
            out.append(("ok", f"Precision {p[-1]:.2f} и Recall {r[-1]:.2f} сбалансированы",
                        "Модель не склонна ни пропускать объекты, ни выдумывать лишние."))

    if finished:
        out.append(("ok", "Обучение завершено",
                    "Результаты - в папке runs/…: weights/best.pt (лучшая модель), results.png (графики), "
                    "confusion_matrix.png (какие классы путаются). train.py уже сделал и best.onnx - загрузите его в "
                    "«Авторазметка», чтобы модель разметила остальные картинки, исправьте ошибки и переобучите."))
    return out


